#!/usr/bin/env python3
"""Offline, standard-library checks of the archived V04 snapshot. No solver calls."""
from pathlib import Path
from collections import Counter,defaultdict
import argparse,csv,hashlib,json

def check(ok,why):
 if not ok:raise ValueError(why)
def digest(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def readcsv(p):
 with p.open(encoding='utf-8-sig',newline='') as f:return list(csv.DictReader(f))
def verify(root):
 checks={};hf=root/'SHA256_MANIFEST.json'
 if hf.exists():
  hashes=json.loads(hf.read_text())
  for name,h in hashes.items():check(digest(root/name)==h,'Checksum mismatch: '+name)
  checks['file_checksums']=len(hashes)
 bm=readcsv(root/'metadata/BENCHMARK_MANIFEST_85.csv');rows=readcsv(root/'metadata/EXPERIMENT_MANIFEST_510.csv')
 check(len(bm)==85 and len(rows)==510,'Panel shape')
 benches={b['instance']:b for b in bm};check(len(benches)==85,'Duplicate benchmark identity')
 refs={}
 for b in bm:
  ip=root/b['input_path'];op=root/b['oracle_path']
  check(digest(ip)==b['input_sha256'],'Input SHA: '+b['instance'])
  check(digest(op)==b['oracle_file_sha256'],'Oracle SHA: '+b['instance'])
  ref=json.loads(op.read_text());pts=ref.get('pareto_points',ref.get('objective_vectors'))
  check(pts is not None,'Missing reference vectors')
  refs[b['instance']]={tuple(map(int,y)) for y in pts}
  check(len(refs[b['instance']])==int(b['pareto_size']),'Reference cardinality')
 groups=defaultdict(dict);counts=Counter();versions=Counter();feasible=0
 for r in rows:
  ident=(r['instance'],int(r['workers']),r['method']);label='/'.join(map(str,ident))
  check(ident[2] not in groups[ident[:2]],'Duplicate cell: '+label)
  p=root/r['terminal_path'];check(digest(p)==r['terminal_sha256'],'Terminal SHA: '+label)
  d=json.loads(p.read_text());ct=d['counters'];f=int(ct['feasible']);i=int(ct['infeasible']);m=int(ct['milp_calls'])
  check((d['instance'],int(d['workers']),d['method'])==ident,'Terminal identity')
  check(d['status']=='EXACT_QA_PASS' and d['exact_reference_match'] is True,'Accepted exact status: '+label)
  check(d['in_flight_or_queued_at_exit']==0 and d.get('resume_count',0)==0,'Incomplete/resumed cell: '+label)
  check(d['input_file_sha256']==r['input_sha256']==benches[r['instance']]['input_sha256'],'Terminal input identity')
  got={tuple(map(int,y)) for y in d['observed_pareto_vectors']}
  check(got==refs[r['instance']],'Full Pareto set mismatch: '+label)
  check(len(got)==d['observed_pareto_size']==int(r['pareto']),'Observed Pareto count')
  check(int(ct['scalarizations'])==f+i==int(r['scalarizations']),'Scalarization identity')
  check(m==(int(r['p'])-(r['method']=='block2'))*f+i==int(r['MILP']),'MILP identity: '+label)
  check(abs(float(d['elapsed_s'])-float(r['wall_s']))<0.0000006,'Elapsed time mismatch: '+label)
  check(d['run_source_sha256']==r['runner_sha256'],'Runner identity in metadata')
  if (root/'src').exists():check(digest(root/r['runner_path'])==r['runner_sha256'],'Archived runner bytes')
  groups[ident[:2]][ident[2]]=(m,f,i,len(got))
  counts[r['family']]+=1;versions[(d['python'],d['scipy_version'],d['numpy_version'])]+=1
 for key,g in groups.items():
  check(set(g)=={'standard','block2'},'Missing paired method')
  a,b=g['standard'],g['block2'];check(a[1:]==b[1:] and a[0]-b[0]==a[1],'Paired work/call identity')
 for ins in benches:
  g=[groups[(ins,w)] for w in (1,2,4)]
  check(g[0]==g[1]==g[2],'Worker work invariance: '+ins)
 a=sum(g['standard'][0] for (ins,w),g in groups.items() if w==1)
 b=sum(g['block2'][0] for (ins,w),g in groups.items() if w==1)
 check((a,b)==(179507,135892),'V04 aggregate call totals')
 tsp=readcsv(root/'data/analysis_inputs/ALL_EXACT_TERMINALS_V27.csv')
 bykey={(r['instance'],int(r['workers']),r['method']):r for r in rows}
 for r in tsp:check(r['terminal_sha256']==bykey[(r['instance'],int(r['workers']),r['method'])]['terminal_sha256'],'V27 source terminal hash')
 for native_row in readcsv(root/'metadata/TSP_NATIVE_LP_MANIFEST.csv'):check(digest(root/native_row['path'])==native_row['sha256'],'Native TSP LP hash')
 checks.update(status='PASS',benchmarks=85,method_pairs=len(groups),raw_terminals=510,full_terminal_reference_set_comparisons=510,terminal_counts_by_family=dict(counts),native_TSP_LP_files=15,standard_MILP_once_per_benchmark=a,block2_MILP_once_per_benchmark=b,MILP_saved=a-b,saving_percent=100*(a-b)/a,recorded_environments=[dict(python=k[0],scipy=k[1],numpy=k[2],terminals=v) for k,v in sorted(versions.items())],new_solver_runs=0,new_oracle_enumerations=0,scope='Byte checks, full archived terminal/reference set equality, completion flags, source identity and count formulas. Reference sets are supplied archived evidence; they were not regenerated by this script. Search node-set identity is not asserted.')
 return checks
def main():
 p=Path(__file__).resolve().parent;default=p if (p/'metadata').exists() else p.parent
 a=argparse.ArgumentParser(description=__doc__);a.add_argument('--root',type=Path,default=default);a.add_argument('--report',type=Path);v=a.parse_args()
 result=verify(v.root.resolve());text=json.dumps(result,indent=2)+'\n'
 if v.report:v.report.parent.mkdir(parents=True,exist_ok=True);v.report.write_text(text)
 print(text)
if __name__=='__main__':main()
